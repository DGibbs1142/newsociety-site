#!/usr/bin/env bash
# Bundle everything this project needs that `git clone` does NOT carry, so the
# whole working session can be rebuilt on another Mac.
#
#   ./integrations/migrate-to-new-mac.sh          # everything, incl. all chat history
#   ./integrations/migrate-to-new-mac.sh --lean   # memory + 5 newest transcripts only
#
# Produces ~/Downloads/newsociety-migration-<date>.tar.gz with a RESTORE.sh inside.
set -euo pipefail

MODE=full
case "${1:-}" in
  --lean) MODE=lean ;;
  --full|"") MODE=full ;;
  *) echo "usage: $0 [--full|--lean]" >&2; exit 2 ;;
esac

PROJECT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CAROUSELS="$HOME/Downloads/NewSociety carousels"
KEY="$(printf '%s' "$PROJECT" | sed 's/[/ ]/-/g')"
CLAUDEDIR="$HOME/.claude/projects/$KEY"
ORIGIN="$(git -C "$PROJECT" remote get-url origin)"

say() { printf '%s\n' "$*"; }
warn() { printf '  !! %s\n' "$*" >&2; }

say "== preflight =="
# The new Mac clones from GitHub, so anything not pushed would be lost.
# Tracked edits must be pushed -- the new Mac clones from GitHub, so anything
# committed-but-unpushed or modified-but-uncommitted would simply vanish.
TRACKED_DIRTY="$(git -C "$PROJECT" status --porcelain --untracked-files=no)"
if [ -n "$TRACKED_DIRTY" ]; then
  warn "UNCOMMITTED CHANGES to tracked files in $PROJECT -- commit and push first."
  printf '%s\n' "$TRACKED_DIRTY" | sed 's/^/     /'
  exit 1
fi
# Untracked files aren't on GitHub either, but they're no reason to refuse --
# carry them in the bundle so nothing is silently left behind.
UNTRACKED="$(git -C "$PROJECT" ls-files --others --exclude-standard)"
if [ -n "$UNTRACKED" ]; then
  warn "untracked (not on GitHub) -- riding along in repo-private/untracked/:"
  printf '%s\n' "$UNTRACKED" | sed 's/^/     /'
fi
git -C "$PROJECT" fetch --quiet origin 2>/dev/null || warn "could not reach origin; sync check skipped"
if LOCAL=$(git -C "$PROJECT" rev-parse @ 2>/dev/null) && REMOTE=$(git -C "$PROJECT" rev-parse @'{u}' 2>/dev/null); then
  if [ "$LOCAL" != "$REMOTE" ]; then
    warn "local branch differs from origin -- push first, or unpushed commits are lost"
    exit 1
  fi
  say "  repo clean and in sync with origin ($(git -C "$PROJECT" rev-parse --short @))"
fi
[ -d "$CAROUSELS" ] || warn "no carousels dir at $CAROUSELS"
[ -d "$CLAUDEDIR" ] || warn "no claude project dir at $CLAUDEDIR"

STAGE="$(mktemp -d)"; trap 'rm -rf "$STAGE"' EXIT
B="$STAGE/newsociety-migration"
mkdir -p "$B/carousels" "$B/repo-private/.claude" "$B/claude-project"

say "== collecting =="
# 1. carousel builders + rendered sets, which live OUTSIDE the repo entirely
if [ -d "$CAROUSELS" ]; then
  rsync -a --exclude '.chrome-*' --exclude '.src' --exclude '.DS_Store' \
        "$CAROUSELS/" "$B/carousels/"
  say "  carousels          $(du -sh "$B/carousels" | cut -f1)"
fi

# 2. git-ignored files inside the repo
[ -f "$PROJECT/config.local.js" ] && cp "$PROJECT/config.local.js" "$B/repo-private/"
[ -f "$PROJECT/.claude/settings.local.json" ] && cp "$PROJECT/.claude/settings.local.json" "$B/repo-private/.claude/"
if [ -n "$UNTRACKED" ]; then
  mkdir -p "$B/repo-private/untracked"
  printf '%s\n' "$UNTRACKED" | rsync -a --files-from=- "$PROJECT" "$B/repo-private/untracked/"
  say "  untracked files    $(printf '%s\n' "$UNTRACKED" | wc -l | tr -d ' ')"
fi
if [ -d "$PROJECT/social-drafts" ]; then
  rsync -a --exclude '.DS_Store' "$PROJECT/social-drafts/" "$B/repo-private/social-drafts/"
  say "  social-drafts      $(du -sh "$B/repo-private/social-drafts" | cut -f1)"
fi

# 3. memory + chat history (the memory dir is what makes the next session not start cold)
if [ -d "$CLAUDEDIR" ]; then
  rsync -a "$CLAUDEDIR/memory/" "$B/claude-project/memory/" 2>/dev/null || true
  say "  memory             $(du -sh "$B/claude-project/memory" 2>/dev/null | cut -f1) ($(ls -1 "$B/claude-project/memory"/*.md 2>/dev/null | wc -l | tr -d ' ') files)"
  if [ "$MODE" = full ]; then
    rsync -a --exclude 'memory' "$CLAUDEDIR/" "$B/claude-project/"
  else
    # newest 5 transcripts, plus each one's sidecar dir if present
    ls -1t "$CLAUDEDIR"/*.jsonl 2>/dev/null | head -5 | while read -r f; do
      cp "$f" "$B/claude-project/"
      run="$(basename "$f" .jsonl)"
      [ -d "$CLAUDEDIR/$run" ] && rsync -a "$CLAUDEDIR/$run" "$B/claude-project/"
    done
  fi
  say "  history ($MODE)     $(du -sh "$B/claude-project" | cut -f1), $(ls -1 "$B/claude-project"/*.jsonl 2>/dev/null | wc -l | tr -d ' ') transcripts"
fi

cat > "$B/MANIFEST.txt" <<MEOF
NewSociety migration bundle
built     $(date '+%Y-%m-%d %H:%M %Z') on $(hostname -s)
mode      $MODE
origin    $ORIGIN
commit    $(git -C "$PROJECT" rev-parse @)
src path  $PROJECT
mem key   $KEY

Run RESTORE.sh on the new Mac. Not included, by design:
  node_modules/, .netlify/   regenerated by npm install / netlify link
  Chrome sign-ins            sign in yourself on the new Mac
MEOF

cat > "$B/RESTORE.sh" <<'RESTORE_EOF'
#!/usr/bin/env bash
# Rebuild the NewSociety working session on this Mac.
#   ./RESTORE.sh                      -> ~/Downloads/newsociety-site 3
#   ./RESTORE.sh "/some/other/path"
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT="${1:-$HOME/Downloads/newsociety-site 3}"
ORIGIN="$(awk '/^origin/{print $2}' "$HERE/MANIFEST.txt")"

say() { printf '%s\n' "$*"; }

say "== repo =="
if [ -d "$PROJECT/.git" ]; then
  say "  already present: $PROJECT"
else
  mkdir -p "$(dirname "$PROJECT")"
  git clone "$ORIGIN" "$PROJECT"
fi

say "== git-ignored files =="
[ -f "$HERE/repo-private/config.local.js" ] && cp "$HERE/repo-private/config.local.js" "$PROJECT/" && say "  config.local.js"
if [ -f "$HERE/repo-private/.claude/settings.local.json" ]; then
  mkdir -p "$PROJECT/.claude"
  cp "$HERE/repo-private/.claude/settings.local.json" "$PROJECT/.claude/"
  say "  .claude/settings.local.json"
fi
[ -d "$HERE/repo-private/social-drafts" ] && rsync -a "$HERE/repo-private/social-drafts/" "$PROJECT/social-drafts/" && say "  social-drafts/"
[ -d "$HERE/repo-private/untracked" ] && rsync -a "$HERE/repo-private/untracked/" "$PROJECT/" && say "  untracked files"

say "== carousel builders =="
if [ -d "$HERE/carousels" ]; then
  mkdir -p "$HOME/Downloads/NewSociety carousels"
  rsync -a "$HERE/carousels/" "$HOME/Downloads/NewSociety carousels/"
  say "  -> $HOME/Downloads/NewSociety carousels"
fi

# The memory/history folder name is derived from the project path AND this
# Mac's username, so recompute it here rather than reusing the old one.
KEY="$(printf '%s' "$PROJECT" | sed 's/[/ ]/-/g')"
DEST="$HOME/.claude/projects/$KEY"
say "== memory + chat history =="
say "  key $KEY"
mkdir -p "$DEST"
[ -d "$HERE/claude-project" ] && rsync -a "$HERE/claude-project/" "$DEST/"
say "  -> $DEST"
say "     $(ls -1 "$DEST"/memory/*.md 2>/dev/null | wc -l | tr -d ' ') memory files, $(ls -1 "$DEST"/*.jsonl 2>/dev/null | wc -l | tr -d ' ') transcripts"

say ""
say "== left for you =="
CHROME="/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
if [ -x "$CHROME" ]; then say "  [ok] Chrome found (carousel rendering needs it)"
else say "  [!!] INSTALL Google Chrome -- nsbrand.py renders every slide with it"; fi
command -v python3 >/dev/null && say "  [ok] python3 $(python3 -V 2>&1 | cut -d' ' -f2)" || say "  [!!] install python3"
say "  [ ] sign in to X / Instagram / Business Suite / TikTok in Chrome"
say "  [ ] cd into the project and run: npm install"
say "  [ ] netlify link   (restores .netlify/)"
say "  [ ] open the folder in Claude Code -- history and memory will be there"
RESTORE_EOF
chmod +x "$B/RESTORE.sh"

OUT="$HOME/Downloads/newsociety-migration-$(date +%Y%m%d).tar.gz"
say "== packing =="
COPYFILE_DISABLE=1 tar -czf "$OUT" -C "$STAGE" newsociety-migration
say "  $OUT"
say "  $(du -sh "$OUT" | cut -f1)"
